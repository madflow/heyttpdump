import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";

for (const [app, env, output] of [
  ["api", "ApiEnv", "apps/api/worker-configuration.d.ts"],
  ["dump", "DumpEnv", "apps/dump/worker-configuration.d.ts"],
  ["web", "WebEnv", "apps/web/src/worker-configuration.d.ts"],
]) {
  const result = spawnSync(
    process.execPath,
    [
      "node_modules/wrangler/bin/wrangler.js",
      "types",
      "-c",
      `apps/${app}/wrangler.jsonc`,
      "--env-interface",
      env,
      "--include-runtime=false",
      output,
    ],
    { stdio: "inherit" },
  );
  if (result.status !== 0) process.exit(result.status ?? 1);
  if (app === "web") {
    // Exclude generated entry-module references for deterministic checked-in types.
    // Exclude that import and its source hash so clean and built checkouts match,
    // and checkJs never follows the generated frontend bundle into type checking.
    const source = await readFile(output, "utf8");
    await writeFile(
      output,
      source
        .replace(/\tinterface GlobalProps \{\n\t\tmainModule:[^\n]*\n\t\}\n/, "")
        .replace(/^(\/\/ Generated by Wrangler[^\n]*) \(hash: [a-f0-9]+\)$/m, "$1"),
    );
  }
}
